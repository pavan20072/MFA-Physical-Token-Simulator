function updateOtpCountdown() {
  if (!otpExpiresAt) {
    $("otpCountdown").textContent = "60s";
    return;
  }

  const remaining = Math.max(
    0,
    Math.ceil((otpExpiresAt - Date.now()) / 1000)
  );

  $("otpCountdown").textContent = remaining + "s";

  if (
    remaining === 0 &&
    !$("otpStep").classList.contains("hidden-step")
  ) {
    $("otpState").textContent = "EXPIRED";
  }
}

// Start the token simulator and countdown.
