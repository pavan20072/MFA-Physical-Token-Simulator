const LAMBDA_URL = "https://6i6mpbc7rwme7chlhtw6nvceku0edfnm.lambda-url.us-east-1.on.aws/ ";

let attempts = 0;
let lastWindow = -1;
let generatedOtp = "";
let otpExpiresAt = 0;
let verifiedNumber = false;
let registeredNumber = "";

function makeToken(windowNo) {
  let x = Math.imul(windowNo ^ 0x5f3759df, 2654435761) >>> 0;
  x ^= x >>> 16;
  x = Math.imul(x, 2246822519) >>> 0;
  x ^= x >>> 13;
  return String(x % 1000000).padStart(6, "0");
}

function currentData() {
  const now = Math.floor(Date.now() / 1000);
  const win = Math.floor(now / 30);
  return {
    code: makeToken(win),
    remaining: 30 - (now % 30),
    win
  };
}

function updateToken() {
  const d = currentData();

  $("tokenCode").textContent = d.code;
  $("heroOtp").textContent = d.code;
  $("bigToken").textContent = d.code;
  $("tokenSeconds").textContent = d.remaining;
  $("bigSeconds").textContent = d.remaining;
  $("mfaCountdown").textContent = d.remaining + "s";

  if (lastWindow !== d.win) {
    lastWindow = d.win;
    $("mfaResult").textContent =
      "New MFA token generated. Enter the current token.";
    $("mfaResult").className = "result neutral";
  }
}

function validIndianNumber(number) {
  return /^[6-9]\d{9}$/.test(number);
}

function maskNumber(number) {
  return "+91 " + number.slice(0, 2) +
    "XXXXXX" + number.slice(-2);
}

// Call the AWS Lambda Function URL.
async function requestOtp(action, otp = "") {
  if (
    LAMBDA_URL === "PASTE_YOUR_LAMBDA_FUNCTION_URL_HERE" ||
    !LAMBDA_URL.startsWith("https://")
  ) {
    throw new Error("Add your AWS Lambda Function URL at the top of script.js.");
  }

  const response = await fetch(LAMBDA_URL, {
    method: "POST",
    headers: {
      "Content-Type": "application/json"
    },
    body: JSON.stringify({ action, otp })
  });

  let data;

  try {
    data = await response.json();
  } catch {
    throw new Error("Lambda returned an unreadable response.");
  }

  if (!response.ok) {
    throw new Error(data.message || "OTP request failed.");
  }

  return data;
}

// Generate an OTP using Lambda.
async function sendOtp() {
  const number = $("registerNumber").value.replace(/\D/g, "");
  $("registerNumber").value = number;

  if (!validIndianNumber(number)) {
    show(
      "sendResult",
      "Enter a valid 10-digit Indian mobile number.",
      "error"
    );
    $("authState").textContent = "NUMBER INVALID";
    return;
  }

  registeredNumber = number;
  $("sendOtpBtn").disabled = true;

  show("sendResult", "Requesting OTP from AWS...", "neutral");

  try {
    const data = await requestOtp("generate");
    const otp = String(data.demoOTP || "");

    if (!/^\d{6}$/.test(otp)) {
      throw new Error("Lambda did not return a six-digit demo OTP.");
    }

    generatedOtp = otp;
    otpExpiresAt = Date.now() +
      (Number(data.expiresInSeconds) || 120) * 1000;

    verifiedNumber = false;

    $("maskedNumber").textContent = maskNumber(number);
    $("otpStep").classList.remove("hidden-step");
    $("otpState").textContent = "SENT";
    $("authState").textContent = "OTP GENERATED";
    $("authSub").textContent = "Enter the demo OTP";

    // Classroom demonstration only. This does NOT send an SMS.
    $("demoOtp").textContent = "DEMO OTP: " + generatedOtp;
    $("demoOtp").classList.remove("hidden-step");

    show(
      "sendResult",
      "Demo OTP generated by AWS Lambda. No SMS was sent.",
      "success"
    );
  } catch (error) {
    show(
      "sendResult",
      "Could not generate OTP: " + error.message,
      "error"
    );
  } finally {
    $("sendOtpBtn").disabled = false;
  }
}

// Verify the entered OTP using Lambda.
async function verifyOtp() {
  const entered = $("smsOtpInput").value.trim();

  if (!/^\d{6}$/.test(entered)) {
    show("otpResult", "OTP must contain exactly 6 digits.", "error");
    return;
  }

  if (!otpExpiresAt || Date.now() > otpExpiresAt) {
    show("otpResult", "OTP expired. Please request a new OTP.", "error");
    $("otpState").textContent = "EXPIRED";
    return;
  }

  $("verifyOtpBtn").disabled = true;
  show("otpResult", "Verifying OTP with AWS Lambda...", "neutral");

  try {
    const data = await requestOtp("verify", entered);

    attempts++;
    $("attempts").textContent = attempts;

    if (!data.verified) {
      verifiedNumber = false;

      show(
        "otpResult",
        data.message || "Invalid or expired OTP.",
        "error"
      );

      $("otpState").textContent = "INVALID";
      return;
    }

    verifiedNumber = true;

    show("otpResult", "OTP verified by AWS Lambda.", "success");

    $("otpState").textContent = "VERIFIED";
    $("authState").textContent = "OTP VERIFIED";
    $("authSub").textContent = "Ready for MFA token";
    $("mfaState").textContent = "UNLOCKED";

    $("tokenStep").classList.remove("hidden-step");
    $("demoOtp").textContent = "OTP verified successfully.";
  } catch (error) {
    show(
      "otpResult",
      "Verification failed: " + error.message +
      ". Check Lambda CORS and OTP storage.",
      "error"
    );
  } finally {
    $("verifyOtpBtn").disabled = false;
  }
}

// Generate a replacement OTP using Lambda.
async function resendOtp() {
  if (!registeredNumber) return;

  $("resendOtpBtn").disabled = true;

  try {
    const data = await requestOtp("generate");
    const otp = String(data.demoOTP || "");

    if (!/^\d{6}$/.test(otp)) {
      throw new Error("Lambda did not return a six-digit demo OTP.");
    }

    generatedOtp = otp;
    otpExpiresAt = Date.now() +
      (Number(data.expiresInSeconds) || 120) * 1000;

    verifiedNumber = false;
    $("smsOtpInput").value = "";
    $("otpState").textContent = "RESENT";

    show(
      "otpResult",
      "New demo OTP generated. No SMS was sent.",
      "neutral"
    );

    $("demoOtp").textContent = "DEMO OTP: " + generatedOtp;
    $("demoOtp").classList.remove("hidden-step");
  } catch (error) {
    show(
      "otpResult",
      "Could not resend OTP: " + error.message,
      "error"
    );
  } finally {
    $("resendOtpBtn").disabled = false;
  }
}

// Existing 30-second MFA token simulator.
function verifyMfa() {
  attempts++;
  $("attempts").textContent = attempts;

  if (!verifiedNumber) {
    show(
      "mfaResult",
      "Verify the OTP before entering the MFA token.",
      "error"
    );
    return;
  }

  const entered = $("mfaInput").value.trim();
  const d = currentData();

  if (!/^\d{6}$/.test(entered)) {
    show("mfaResult", "MFA token must contain exactly 6 digits.", "error");
    return;
  }

  if (entered !== d.code) {
    show(
      "mfaResult",
      "Invalid or expired MFA token. Access rejected.",
      "error"
    );

    $("authState").textContent = "REJECTED";
    $("authSub").textContent = "MFA verification failed";
    return;
  }

  show(
    "mfaResult",
    "Demo authentication successful — access granted.",
    "success"
  );

  $("authState").textContent = "AUTHENTICATED";
  $("authSub").textContent = "Demo authentication checks passed";
  $("mfaState").textContent = "VERIFIED";
}

function show(id, msg, cls) {
  $(id).textContent = msg;
  $(id).className = "result " + cls;
}

